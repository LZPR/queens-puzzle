/* ============================================================================
 * looks/mono.js · 棋盘滤镜「黑白」
 * ----------------------------------------------------------------------------
 * 给整块棋盘套一层 CSS filter（grayscale）：格子、色块描边、× 、皇后、圈画
 * 一起褪成灰度，只留下明暗。棋盘**外面**的东西（色卡、信息条、工具栏、
 * 背景动画）一点不受影响 —— 滤镜挂在 .board 上，不挂在页面上。
 *
 * 顺序有讲究：这一类第一项是「无」。滤镜这事得**默认关着** ——
 * 一开局就把整盘颜色抽掉，等于把「色块靠颜色分」这条最要紧的线索藏起来。
 * 所以「无」是出厂默认（自动就免费），「黑白」是一份要靠抽奖拿的奖品。
 *
 * 滤镜的值就写在这一条的 `filter` 字段上，ui/effects.js 直接挂到 .board 上——
 * 样式表里不认任何一套滤镜的 id，以后加滤镜只改插件。
 * ========================================================================== */

export default {
  id: 'mono',
  name: '黑白',
  note: '整块棋盘褪成灰度',
  filters: [
    { id: 'none', name: '无', prize: false, filter: '', desc: '棋盘保持原色' },
    /* 光 grayscale 会把整盘压成一片浅灰；brightness(.9) 让它沉一口，
     * contrast(1.1) 再把相邻色块的明度差拉开一点 —— 实测这几档里
     * 只有这一组既保住了层次、又没把浅色块冲成纯白（1.3 / .88 那组会冲白，
     * 光 grayscale 那组太飘）。 */
    { id: 'mono', name: '黑白', filter: 'grayscale(1) contrast(1.1) brightness(.9)', desc: '整块棋盘褪成灰度，只留下明暗' }
  ]
};
